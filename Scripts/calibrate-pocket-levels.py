#!/usr/bin/env python3
"""Freeze catalog-pinned Max level profiles from calibration passages only.

Inputs are hash-verified BS.1770 reports from measure-voice-levels.py. Holdout
rows are deliberately excluded from all gain and peak-headroom decisions.
"""
import argparse
import hashlib
import json
import math
import statistics
import struct
from pathlib import Path

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('reports', nargs='+', type=Path)
p.add_argument('--policy', type=Path, default=Path('docs/loudness-review/targets.json'))
p.add_argument('--catalog', type=Path, default=Path('Sources/KokoroCatalog/PocketTTS'))
p.add_argument('--swift', type=Path, default=Path('Sources/KokoroNarration/PocketNarrationLevelProfiles.swift'))
p.add_argument('--output', type=Path, default=Path('docs/loudness-review/profiles.json'))
a = p.parse_args()
policy = json.loads(a.policy.read_text())
rows = []
for path in a.reports:
    report = json.loads(path.read_text())
    assert report['complete'], path
    rows += report['rows']
# Pin all source manifests as well as gains in the prepared-audio revision.
manifest_hashes = {}
expected = set()
for language in ['en', 'es', 'fr', 'de', 'pt', 'it', 'nl']:
    for name in [language, 'delivery-' + language]:
        path = a.catalog / (name + '.json')
        manifest_hashes[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        manifest = json.loads(path.read_text())
        for item in manifest['installedFiles']:
            path = Path(item['path'])
            if path.parent.name != 'embeddings' or path.suffix != '.safetensors':
                continue
            voice, _, style = path.stem.partition('__')
            expected.add(f'pocket-{voice}-{language}-v1|{style or "original"}')
assert len(expected) == 525, len(expected)
calibration = {}
for r in rows:
    if r['split'] != 'calibration':
        continue
    key = r['voiceID'] + '|' + r.get('style', 'original')
    calibration.setdefault((r['backend'], key), []).append(r)
assert 0 < policy['softKneeSampleAmplitude'] < policy['softCeilingSampleAmplitude'] < 1
profiles = {}
for key in sorted(expected):
    backend = 'coreml-cpu' if ('coreml-cpu', key) in calibration else 'mlx-cpu'
    group = calibration[(backend, key)]
    assert len(group) == 3 and {r['passage'] for r in group} == {0, 1, 2}, key
    level = statistics.median(r['integratedLUFS'] for r in group)
    peak = max(r['truePeakDBFS'] for r in group)
    voice, style = key.split('|')
    offset = 0
    if style not in ('original', 'neutral'):
        neutral = calibration[(backend, voice + '|neutral')]
        assert len(neutral) == 3
        difference = level - statistics.median(r['integratedLUFS'] for r in neutral)
        bound = policy['maximumReferenceStyleOffsetLU']
        offset = max(-bound, min(bound, difference))
    target = policy['neutralTargetLUFS'] + offset
    gain_db = max(policy['minimumGainDB'], min(policy['maximumBoostDB'], target - level,
                  -policy['calibrationTruePeakHeadroomDB'] - peak))
    gain = struct.unpack('<f', struct.pack('<f', 10 ** (gain_db / 20)))[0]
    assert math.isfinite(gain) and 0 < gain <= 10 ** (policy["maximumBoostDB"] / 20) * (1 + 1e-7)
    profiles[key] = dict(backend=backend, calibrationMedianLUFS=level,
                         calibrationMaxTruePeakDBFS=peak, targetLUFS=target,
                         styleOffsetLU=offset, gainDB=20 * math.log10(gain), gain=gain,
                         gainBits=struct.unpack('<I', struct.pack('<f', gain))[0])
audio_policy = {key: policy[key] for key in ['neutralTargetLUFS', 'maximumBoostDB', 'minimumGainDB',
    'maximumReferenceStyleOffsetLU', 'calibrationTruePeakHeadroomDB',
    'softKneeSampleAmplitude', 'softCeilingSampleAmplitude']}
identity = dict(algorithm='constant-f32-gain-boost-only-exponential-knee-v1',
                policy=audio_policy, manifests=manifest_hashes,
                gains={k: v['gainBits'] for k, v in profiles.items()})
digest = hashlib.sha256(json.dumps(identity, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
revision = 'pocket-level-v1-' + digest[:16]
a.output.write_text(json.dumps(dict(revision=revision, identity=identity, profiles=profiles), indent=2) + '\n')
swift = ['// Generated by Scripts/calibrate-pocket-levels.py. Do not hand-edit.',
         '// Catalog-pinned calibration only; holdout audio never selects gains.',
         'package enum PocketNarrationLevelProfiles {',
         f'    package static let revision = "{revision}"',
         f'    package static let softKnee: Double = {policy["softKneeSampleAmplitude"]!r}',
         f'    package static let softKneeWidth: Double = {policy["softCeilingSampleAmplitude"] - policy["softKneeSampleAmplitude"]!r}',
         '    package static let gains: [String: Float] = [']
for key, profile in profiles.items():
    swift.append(f'        "{key}": Float(bitPattern: 0x{profile["gainBits"]:08x}),')
swift += ['    ]', '}', '']
a.swift.write_text('\n'.join(swift))
print(revision, len(profiles), 'profiles')
